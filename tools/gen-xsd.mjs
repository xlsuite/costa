#!/usr/bin/env node
// Generates schemas/costa-2.0.xsd from schemas/costa-2.0.schema.json.
// The XSD checks structure, types, enumerations, patterns and cardinality. Rules that
// XSD 1.0 cannot express (oneOf, cross-field conditions, regulatory checks) are left to
// the JSON Schema and tools/validate.mjs. Run with --check to verify the committed XSD is current.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, NS, DEFS, SKIP, deref, refName } from './xml.mjs';

const OBJECT_DEFS = Object.keys(DEFS).filter((k) => DEFS[k].type === 'object');
const SIMPLE_DEFS = Object.keys(DEFS).filter((k) => DEFS[k].type !== 'object' && !DEFS[k].oneOf);
const xesc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const xsdPattern = (p) => p.replace(/^\^/, '').replace(/\$$/, '');

function simpleBody(s, ind) {
  const t = Array.isArray(s.type) ? s.type.find((x) => x !== 'null') : s.type;
  if (s.enum) return [`${ind}<xs:restriction base="xs:string">`, ...s.enum.map((e) => `${ind}  <xs:enumeration value="${xesc(e)}"/>`), `${ind}</xs:restriction>`];
  if (s.const !== undefined) return [`${ind}<xs:restriction base="xs:string">`, `${ind}  <xs:enumeration value="${xesc(s.const)}"/>`, `${ind}</xs:restriction>`];
  let base = 'xs:string';
  const facets = [];
  if (t === 'string') {
    if (s.format === 'date') base = 'xs:date';
    else if (s.format === 'date-time') base = 'xs:dateTime';
    else if (s.format === 'uri') base = 'xs:anyURI';
    if (s.pattern) facets.push(`<xs:pattern value="${xesc(xsdPattern(s.pattern) + (s.pattern.endsWith('$') ? '' : '.*'))}"/>`);
    if (s.format === 'email') facets.push('<xs:pattern value="[^@\\s]+@[^@\\s]+\\.[^@\\s]+"/>');
    if (s.minLength !== undefined) facets.push(`<xs:minLength value="${s.minLength}"/>`);
    if (s.maxLength !== undefined) facets.push(`<xs:maxLength value="${s.maxLength}"/>`);
  } else if (t === 'number' || t === 'integer') {
    base = t === 'integer' ? 'xs:integer' : 'xs:decimal';
    if (s.minimum !== undefined) facets.push(`<xs:minInclusive value="${s.minimum}"/>`);
    if (s.exclusiveMinimum !== undefined) facets.push(`<xs:minExclusive value="${s.exclusiveMinimum}"/>`);
  } else if (t === 'boolean') base = 'xs:boolean';
  if (!facets.length) return null;
  return [`${ind}<xs:restriction base="${base}">`, ...facets.map((f) => `${ind}  ${f}`), `${ind}</xs:restriction>`];
}

function plainType(s) {
  const t = Array.isArray(s.type) ? s.type.find((x) => x !== 'null') : s.type;
  if (t === 'string') return s.format === 'date' ? 'xs:date' : s.format === 'date-time' ? 'xs:dateTime' : s.format === 'uri' ? 'xs:anyURI' : 'xs:string';
  if (t === 'integer') return 'xs:integer';
  if (t === 'number') return 'xs:decimal';
  if (t === 'boolean') return 'xs:boolean';
  return 'xs:string';
}

function element(name, pdef, required, ind) {
  const isArr = pdef.type === 'array';
  const item = isArr ? pdef.items : pdef;
  const min = required ? (isArr ? Math.max(1, pdef.minItems || 0) : 1) : 0;
  const occ = `${min === 1 ? '' : ` minOccurs="${min}"`}${isArr ? ` maxOccurs="${pdef.maxItems || 'unbounded'}"` : ''}`;
  const rn = refName(item);
  if (rn) return [`${ind}<xs:element name="${name}" type="costa:${rn}"${occ}/>`];
  const body = simpleBody(item, ind + '    ');
  if (!body) return [`${ind}<xs:element name="${name}" type="${plainType(item)}"${occ}/>`];
  return [`${ind}<xs:element name="${name}"${occ}>`, `${ind}  <xs:simpleType>`, ...body, `${ind}  </xs:simpleType>`, `${ind}</xs:element>`];
}

const out = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<!-- GENERATED by tools/gen-xsd.mjs from schemas/costa-2.0.schema.json. Do not edit by hand. -->',
  '<!-- XSD checks structure only. Regulatory and cross-field rules: JSON Schema + tools/validate.mjs. -->',
  `<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema" xmlns:costa="${NS}" targetNamespace="${NS}" elementFormDefault="qualified">`,
  '',
];
for (const root of ['CostaFeed', 'CostaProduct', 'CostaLot', 'CostaLabReport']) out.push(`  <xs:element name="${root}" type="costa:${root}"/>`);
out.push('');
for (const name of SIMPLE_DEFS) {
  const body = simpleBody(DEFS[name], '    ') || [`    <xs:restriction base="${plainType(DEFS[name])}"/>`];
  out.push(`  <xs:simpleType name="${name}">`, ...body, '  </xs:simpleType>', '');
}
for (const name of OBJECT_DEFS) {
  const d = DEFS[name];
  out.push(`  <xs:complexType name="${name}">`);
  if (name === 'Extensions') {
    out.push('    <xs:sequence>', '      <xs:element name="extension" minOccurs="0" maxOccurs="unbounded">', '        <xs:complexType>', '          <xs:simpleContent>', '            <xs:extension base="xs:string">',
      `              <xs:attribute name="key" use="required"><xs:simpleType><xs:restriction base="xs:string"><xs:pattern value="${xesc(xsdPattern(d.propertyNames.pattern))}"/></xs:restriction></xs:simpleType></xs:attribute>`,
      '            </xs:extension>', '          </xs:simpleContent>', '        </xs:complexType>', '      </xs:element>', '    </xs:sequence>');
  } else {
    out.push('    <xs:sequence>');
    for (const [k, p] of Object.entries(d.properties)) if (!SKIP.has(k)) out.push(...element(k, p, (d.required || []).includes(k), '      '));
    out.push('    </xs:sequence>');
  }
  out.push('  </xs:complexType>', '');
}
out.push('</xs:schema>', '');
const xsd = out.join('\n');
const path = join(ROOT, 'schemas/costa-2.0.xsd');
if (process.argv.includes('--check')) {
  const cur = readFileSync(path, 'utf8');
  if (cur !== xsd) { console.error('schemas/costa-2.0.xsd is out of date: run node tools/gen-xsd.mjs'); process.exit(1); }
  console.log('XSD is current');
} else { writeFileSync(path, xsd); console.log(`wrote ${path}`); }
